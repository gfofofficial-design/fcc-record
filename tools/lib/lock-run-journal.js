// BUILD 03 — PERSISTENT LOCK RUN JOURNAL (AD-1, RATIFIED WITH STRENGTHENING).
//
// Authoritative OPERATIONAL journal for Lock Runs:
//   {stagingRoot}/lock-runs/{instrument_id}/state.json    (atomic, fsync'd)
//   {stagingRoot}/lock-runs/{instrument_id}/locked-bytes.bin (write-once)
//
// LAW (from the ratified BUILD 03 architecture + AD-1):
// - This is operational Lock Run state. It is NEVER under record/, never
//   rendered as instrument state, and PUBLICATION_RECONCILIATION_HOLD is
//   an operational condition, not a lifecycle state.
// - Every boundary-crossing send is journaled BEFORE the send, with a
//   CONSERVATIVE default (crossedExternalBoundary=true, outcome PENDING):
//   a crash between journal and transport response must classify UNCERTAIN,
//   never "provably unpublished".
// - Bytes/hash/filed_at are written once at init (design step P6) and are
//   never regenerated by any function in this module. Case A destruction
//   removes them; nothing here can re-mint them.
// - AD-1 STRENGTHENING: absence of this journal is NOT evidence of Case A.
//   Consumers (orchestrator P4 / recovery) must establish prior-publication
//   status from approved-witness evidence and FAIL CLOSED when they cannot.
//   This module therefore exposes hold state but never "cleanliness".
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function lockRunsRoot(stagingRoot) { return path.join(stagingRoot, 'lock-runs'); }
function runDir(stagingRoot, instrumentId) { return path.join(lockRunsRoot(stagingRoot), instrumentId); }
function statePath(stagingRoot, id) { return path.join(runDir(stagingRoot, id), 'state.json'); }
function bytesPath(stagingRoot, id) { return path.join(runDir(stagingRoot, id), 'locked-bytes.bin'); }

// Atomic, durable write: tmp file in same dir -> fsync(file) -> rename ->
// fsync(directory). Survives process crash at any point with either the old
// or the new complete content — never a torn state file.
function atomicDurableWrite(target, buf) {
  const dir = path.dirname(target);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = path.join(dir, `.tmp-${process.pid}-${Date.now()}-${Math.random().toString(36).slice(2)}`);
  const fd = fs.openSync(tmp, 'w');
  try { fs.writeSync(fd, buf); fs.fsyncSync(fd); } finally { fs.closeSync(fd); }
  fs.renameSync(tmp, target);
  const dfd = fs.openSync(dir, 'r');
  try { fs.fsyncSync(dfd); } catch (_) { /* dir fsync unsupported on some platforms; rename already atomic */ }
  fs.closeSync(dfd);
}

function writeState(stagingRoot, id, state) {
  atomicDurableWrite(statePath(stagingRoot, id), Buffer.from(JSON.stringify(state, null, 2) + '\n', 'utf8'));
  return state;
}

function loadRun(stagingRoot, id) {
  const p = statePath(stagingRoot, id);
  if (!fs.existsSync(p)) return null;
  const state = JSON.parse(fs.readFileSync(p, 'utf8'));
  const bp = bytesPath(stagingRoot, id);
  state._bytesPresent = fs.existsSync(bp);
  return state;
}

function loadBytes(stagingRoot, id) {
  const bp = bytesPath(stagingRoot, id);
  if (!fs.existsSync(bp)) return null;
  return fs.readFileSync(bp);
}

function listRuns(stagingRoot) {
  const root = lockRunsRoot(stagingRoot);
  if (!fs.existsSync(root)) return [];
  return fs.readdirSync(root).filter((d) => fs.existsSync(statePath(stagingRoot, d)));
}

// P6 — durable persistence BEFORE any witness send. Refuses to initialize
// over an existing run for the same id: that is exactly the second-hash
// surface the persistent P4 gate exists to police.
function initRun(stagingRoot, { instrumentId, filedAt, lockSha256, canonicalBytes }) {
  if (!instrumentId || !filedAt || !lockSha256 || !canonicalBytes) throw new Error('initRun: missing required fields');
  const existing = loadRun(stagingRoot, instrumentId);
  if (existing) throw new Error(`initRun: journal already exists for ${instrumentId} (phase=${existing.phase}) — second Lock Run for an id with prior state is forbidden here; recovery/P4 governs`);
  const check = crypto.createHash('sha256').update(canonicalBytes).digest('hex');
  if (check !== lockSha256) throw new Error('initRun: lockSha256 does not match canonicalBytes — refusing to persist an inconsistent journal');
  // bytes first (write-once), then state referencing them
  atomicDurableWrite(bytesPath(stagingRoot, instrumentId), canonicalBytes);
  return writeState(stagingRoot, instrumentId, {
    journal_version: 1,
    instrumentId, filedAt, lockSha256,
    phase: 'RUNNING',
    attempts: [],
    commitPoint: null,
    history: [{ at: filedAt, note: 'run initialized; bytes persisted before any send (P6)' }],
  });
}

// Journal an attempt BEFORE the transport call. Conservative defaults:
// once we have decided to send, a crash must read as possibly-published.
function recordAttemptStart(stagingRoot, id, { witness, sentAt, requestMeta }) {
  const st = mustLoad(stagingRoot, id);
  const attempt = {
    witness, sentAt,
    crossedExternalBoundary: true, // conservative until the transport proves otherwise
    outcome: 'PENDING',
    requestMeta: requestMeta || null,
    evidence: null,
  };
  st.attempts.push(attempt);
  writeState(stagingRoot, id, st);
  return st.attempts.length - 1;
}

// Record the transport's actual result for a journaled attempt.
function recordAttemptResult(stagingRoot, id, index, { crossedExternalBoundary, outcome, evidence }) {
  const st = mustLoad(stagingRoot, id);
  const a = st.attempts[index];
  if (!a) throw new Error(`recordAttemptResult: no attempt ${index} for ${id}`);
  if (typeof crossedExternalBoundary === 'boolean') a.crossedExternalBoundary = crossedExternalBoundary;
  if (!['PENDING', 'CONFIRMED_FAILED', 'CONFIRMED_PUBLISHED'].includes(outcome)) throw new Error(`illegal attempt outcome ${outcome}`);
  a.outcome = outcome;
  a.evidence = evidence || null;
  writeState(stagingRoot, id, st);
  return st;
}

function setPhase(stagingRoot, id, phase, extra = {}) {
  const st = mustLoad(stagingRoot, id);
  st.phase = phase;
  Object.assign(st, extra);
  st.history.push({ at: new Date().toISOString(), note: `phase -> ${phase}` });
  writeState(stagingRoot, id, st);
  return st;
}

function recordCommitPoint(stagingRoot, id, commitPoint) {
  const st = mustLoad(stagingRoot, id);
  if (st.commitPoint) {
    // Idempotent only for the identical determination; a DIFFERENT commit
    // point for the same run is an integrity fault, never silently replaced.
    const same = JSON.stringify(st.commitPoint) === JSON.stringify(commitPoint);
    if (!same) throw new Error(`recordCommitPoint: conflicting commit point for ${id}`);
    return st;
  }
  st.commitPoint = commitPoint;
  st.phase = 'COMMIT_POINT_REACHED';
  st.history.push({ at: commitPoint.attestedTime, note: `COMMIT POINT via ${commitPoint.witness}` });
  writeState(stagingRoot, id, st);
  return st;
}

// CASE A destruction: bytes and hash refs destroyed; journal file itself is
// retained as operational history (phase EXPIRED_CASE_A / RESOLVED_RELEASED_CASE_A).
function destroyBytesCaseA(stagingRoot, id, resolvedPhase) {
  const st = mustLoad(stagingRoot, id);
  if (st.commitPoint) throw new Error('destroyBytesCaseA: commit point exists — destruction is unlawful (Correction 1 supreme)');
  const bp = bytesPath(stagingRoot, id);
  if (fs.existsSync(bp)) fs.rmSync(bp);
  st.lockSha256 = null;
  st.filedAt = st.filedAt; // filed_at retained as history of the destroyed run; it can never be reused (fresh runs mint fresh filed_at)
  st.phase = resolvedPhase || 'EXPIRED_CASE_A';
  st.bytesDiscarded = true;
  st.history.push({ at: new Date().toISOString(), note: 'CASE A: bytes + hash destroyed; DRAFT retained; fresh run permitted' });
  writeState(stagingRoot, id, st);
  return st;
}

function mustLoad(stagingRoot, id) {
  const st = loadRun(stagingRoot, id);
  if (!st) throw new Error(`no journal for ${id}`);
  return st;
}

// Authoritative persistent hold map consumed by the proven
// assertSecondHashAllowed(heldStatesById, id) guard (BUILD03_INVARIANT).
// A run is an ACTIVE HOLD iff phase === PUBLICATION_RECONCILIATION_HOLD.
// A run that is RUNNING or COMMIT_POINT_REACHED but not COMPLETED is ALSO
// exposed (as OPEN_RUN) — the orchestrator refuses fresh hashing for those
// too: an in-flight or un-admitted run is never a license for a second hash.
function activeHoldStates(stagingRoot) {
  const holds = {};
  for (const id of listRuns(stagingRoot)) {
    const st = loadRun(stagingRoot, id);
    if (st.phase === 'PUBLICATION_RECONCILIATION_HOLD') holds[id] = { ...st, holdActive: true };
  }
  return holds;
}
function openRunStates(stagingRoot) {
  const open = {};
  for (const id of listRuns(stagingRoot)) {
    const st = loadRun(stagingRoot, id);
    if (['RUNNING', 'COMMIT_POINT_REACHED'].includes(st.phase)) open[id] = st;
  }
  return open;
}

module.exports = {
  lockRunsRoot, runDir, statePath, bytesPath,
  atomicDurableWrite, initRun, loadRun, loadBytes, listRuns,
  recordAttemptStart, recordAttemptResult, setPhase, recordCommitPoint,
  destroyBytesCaseA, activeHoldStates, openRunStates,
};
