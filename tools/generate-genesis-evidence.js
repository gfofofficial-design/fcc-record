#!/usr/bin/env node
// Regenerates governance/evidence/genesis-hash-verification.json with a REAL
// mechanically-observed timestamp captured at the instant this script runs —
// never an invented/declared time. This file lives OUTSIDE governance/frozen/
// deliberately: it is derived, re-verifiable evidence, not a frozen governing
// artifact, so it is exempt from the frozen-document immutability guard by
// construction (same "derived, never authoritative" principle the frozen
// architecture applies to aggregates).
const fs = require('fs'), crypto = require('crypto');
const EXPECTED = {
  'governance/frozen/FCC_PRODUCT_BLUEPRINT_V1_1_1.md': 'e82b16fa5c09c26ca935a67bc5be9e43f36d83372fac895f5a87d7a37ebea77f',
  'governance/frozen/FCC_CAPITAL_DOCTRINE_V0_1_1.md': '65decceac559749e060c9e895ddfa1719a4bdbd04dea6a0924f15135e779f45e',
  'governance/frozen/FCC_CAPITAL_INSTRUMENT_SPEC_V0_1_1.md': 'ac16c70fae1571d890d7dff9218c73cc3f6673892be9491d1d250c82d032beb0',
  'governance/frozen/FCC_STAGE0_IMPLEMENTATION_ARCHITECTURE_V0_1_2.md': 'ddaa2b3d4eafc3e23851be5795443470a26307618eaa2ea06a25fa5b4c36a9da',
};
const observed_at = new Date().toISOString(); // mechanically captured NOW, not a declared date
const documents = Object.entries(EXPECTED).map(([file, expected]) => {
  const actual = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  return { file, expected_sha256: expected, actual_sha256: actual, match: actual === expected };
});
const result = documents.every(d => d.match) ? 'ALL MATCH' : 'MISMATCH DETECTED';
const evidence = {
  note: "hashes_reverified_at reflects the actual wall-clock instant this evidence file was mechanically generated by tools/generate-genesis-evidence.js — it is re-verification evidence, not a claim about the historical genesis instant, which is recorded instead by the git genesis commit itself and its own commit timestamp.",
  hashes_reverified_at: observed_at,
  documents,
  result
};
fs.writeFileSync('governance/evidence/genesis-hash-verification.json', JSON.stringify(evidence, null, 2) + '\n');
console.log('Evidence regenerated at', observed_at, '—', result);
if (result !== 'ALL MATCH') process.exit(1);
